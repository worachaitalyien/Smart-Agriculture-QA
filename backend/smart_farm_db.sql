CREATE DATABASE IF NOT EXISTS smart_farm_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE smart_farm_db;
CREATE TABLE IF NOT EXISTS telemetry_data (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,temperature FLOAT NOT NULL,humidity FLOAT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,CHECK(humidity BETWEEN 0 AND 100)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS warehouse_inventory (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,apple_count INT UNSIGNED NOT NULL DEFAULT 0,
 mango_count INT UNSIGNED NOT NULL DEFAULT 0,orange_count INT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
